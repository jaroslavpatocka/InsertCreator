#!/usr/bin/env python3
"""Stage and publish dist over SFTP on port 222 with a pinned SSH host key.

Credentials are accepted only through FTP_USERNAME / FTP_PASSWORD. Nothing is
deleted on the server. This is a staged, per-file replacement, not an atomic
transaction for the whole website. Run the offline test suite before deploying.
"""

from __future__ import annotations

import argparse
import base64
import binascii
from dataclasses import dataclass
from datetime import datetime, timezone
import errno
import hashlib
import hmac
import io
import json
import logging
import os
from pathlib import Path, PurePosixPath
import posixpath
import re
import socket
import sys
from typing import Mapping


class DeploymentError(Exception):
    """A safe diagnostic that never contains a server response."""


@dataclass(frozen=True)
class UploadFile:
    path: str
    data: bytes


@dataclass(frozen=True)
class DeploymentPlan:
    revision: str
    files: tuple[UploadFile, ...]
    manifest: UploadFile


def validate_relative_path(value: str) -> str:
    """Reject control characters, traversal and ambiguous separators."""
    if not value or "\\" in value or any(ord(char) < 32 or ord(char) == 127 for char in value):
        raise DeploymentError("Invalid relative file path in deployment package.")
    if value.startswith("/") or any(part in ("", ".", "..") for part in value.split("/")):
        raise DeploymentError("Invalid relative file path in deployment package.")
    return value


def validate_remote_dir(value: str, allow_scoped_root: bool = False) -> str:
    if not value or "\\" in value or any(ord(char) < 32 or ord(char) == 127 for char in value):
        raise DeploymentError("DEPLOY_REMOTE_DIR must be an explicit, safe web directory.")
    if value in ("/", "."):
        if not allow_scoped_root:
            raise DeploymentError("Server root requires DEPLOY_ALLOW_SCOPED_ROOT=true and an account restricted to public_html.")
        return value
    parts = value.strip("/").split("/")
    if not all(parts) or any(part in (".", "..") for part in parts) or "//" in value:
        raise DeploymentError("DEPLOY_REMOTE_DIR must not contain traversal or empty path components.")
    return str(PurePosixPath(value))


def build_plan(source: Path, revision: str) -> DeploymentPlan:
    if not re.fullmatch(r"[0-9a-fA-F]{40}", revision):
        raise DeploymentError("Revision must be a full 40-character hexadecimal Git commit ID.")
    revision = revision.lower()
    if source.is_symlink() or getattr(source, "is_junction", lambda: False)() or not source.is_dir():
        raise DeploymentError("Deployment source must be a regular dist directory.")
    source = source.resolve()
    files = []
    for path in sorted(source.rglob("*")):
        if path.is_symlink() or getattr(path, "is_junction", lambda: False)():
            raise DeploymentError("Deployment source must not contain symbolic links or junctions.")
        relative = validate_relative_path(path.relative_to(source).as_posix())
        if ".htaccess" in relative.split("/"):
            # Hosting configuration is managed separately and never replaced.
            continue
        if any(part.startswith(".") for part in relative.split("/")):
            raise DeploymentError("Deployment source must not contain hidden files or directories.")
        if path.is_dir():
            continue
        if not path.is_file():
            raise DeploymentError("Deployment source must contain regular files only.")
        if not path.resolve().is_relative_to(source):
            raise DeploymentError("A deployment file resolves outside the source directory.")
        if relative == "deployment.json":
            raise DeploymentError("deployment.json is generated by the uploader; remove it from dist.")
        # Snapshot bytes once so a changing local file cannot invalidate hashes.
        files.append(UploadFile(relative, path.read_bytes()))
    paths = {file.path for file in files}
    if not {"index.html", "sw.js"}.issubset(paths):
        raise DeploymentError("Deployment package must contain index.html and sw.js.")
    # Entry point and service worker become visible only after their assets.
    priority = {"index.html": 1, "sw.js": 2}
    files.sort(key=lambda file: (priority.get(file.path, 0), file.path))
    manifest = {
        "schemaVersion": 1,
        "revision": revision,
        "generatedAt": datetime.now(timezone.utc).isoformat().replace("+00:00", "Z"),
        "fileCount": len(files),
        "totalBytes": sum(len(file.data) for file in files),
        "files": [
            {"path": file.path, "size": len(file.data), "sha256": hashlib.sha256(file.data).hexdigest()}
            for file in files
        ],
    }
    marker = UploadFile("deployment.json", (json.dumps(manifest, ensure_ascii=True, indent=2) + "\n").encode("utf-8"))
    return DeploymentPlan(revision, tuple(files), marker)


def _safe_pwd(sftp) -> str:
    current = sftp.normalize(".")
    if not isinstance(current, str) or not current.startswith("/") or "\\" in current:
        raise DeploymentError("SFTP server returned an invalid working directory.")
    if any(ord(char) < 32 or ord(char) == 127 for char in current) or ".." in current.split("/"):
        raise DeploymentError("SFTP server returned an invalid working directory.")
    return posixpath.normpath(current)


def _ensure_directories(sftp, root: str, files: tuple[UploadFile, ...]) -> None:
    directories = sorted({str(PurePosixPath(file.path).parent) for file in files} - {"."})
    for directory in directories:
        sftp.chdir(root)
        expected = root
        for part in directory.split("/"):
            expected = posixpath.join(expected, part)
            try:
                sftp.chdir(part)
            except OSError as error:
                if error.errno != errno.ENOENT:
                    raise
                sftp.mkdir(part)
                sftp.chdir(part)
            if _safe_pwd(sftp) != expected:
                raise DeploymentError("A server directory resolves outside its expected deployment path.")
    sftp.chdir(root)


def _host_key_pins(host: str, known_hosts: str) -> tuple[tuple[str, bytes], ...]:
    """Read explicitly provisioned OpenSSH keys, without trust-on-first-use."""
    target = f"[{host}]:222"
    pins = []
    allowed_types = {"ssh-ed25519", "ssh-rsa", "ecdsa-sha2-nistp256", "ecdsa-sha2-nistp384", "ecdsa-sha2-nistp521"}
    for line in known_hosts.splitlines():
        if not line.strip() or line.lstrip().startswith("#"):
            continue
        fields = line.split()
        if len(fields) < 3 or fields[0] != target or fields[1] not in allowed_types:
            raise DeploymentError("FTP_KNOWN_HOSTS must contain verified OpenSSH host-key lines for [FTP_HOST]:222.")
        try:
            wire = base64.b64decode(fields[2], validate=True)
        except (ValueError, binascii.Error):
            raise DeploymentError("FTP_KNOWN_HOSTS contains an invalid host key.") from None
        length = int.from_bytes(wire[:4], "big")
        if length != len(fields[1]) or wire[4:4 + length] != fields[1].encode("ascii") or len(wire) <= 4 + length:
            raise DeploymentError("FTP_KNOWN_HOSTS contains an invalid host key.")
        pins.append((fields[1], wire))
    if not pins:
        raise DeploymentError("Set FTP_KNOWN_HOSTS to an independently verified SSH host key before deployment.")
    return tuple(pins)


def _activate_file(sftp, temporary: str, final_path: str) -> None:
    try:
        sftp.posix_rename(temporary, final_path)
    except OSError as error:
        unsupported = error.errno in (errno.ENOTSUP, errno.EOPNOTSUPP) or str(error).lower() in {
            "operation unsupported", "operation not supported", "unsupported operation",
        }
        if not unsupported:
            raise
        # Standard SFTP rename may reject an existing destination. Never remove
        # that destination to work around a missing POSIX rename extension.
        sftp.rename(temporary, final_path)


def deploy(
    plan: DeploymentPlan,
    *,
    host: str,
    username: str,
    password: str,
    known_hosts: str,
    remote_dir: str = "public_html",
    allow_scoped_root: bool = False,
    ssh_backend=None,
    socket_factory=socket.create_connection,
) -> None:
    """Verify the SSH server identity before sending the password."""
    remote_dir = validate_remote_dir(remote_dir, allow_scoped_root)
    if not host or not re.fullmatch(r"[a-zA-Z0-9](?:[a-zA-Z0-9.-]*[a-zA-Z0-9])?", host):
        raise DeploymentError("FTP_HOST must be a DNS hostname, without a scheme, path or port.")
    if not username or not password:
        raise DeploymentError("Set FTP_USERNAME and FTP_PASSWORD in GitHub Actions secrets.")
    if any(char in username + password for char in ("\r", "\n", "\x00")):
        raise DeploymentError("FTP credentials must not contain control delimiters.")
    pins = _host_key_pins(host, known_hosts)
    connection = transport = sftp = None
    stage = "connection"
    try:
        if ssh_backend is None:
            try:
                import paramiko as ssh_backend
            except ImportError:
                raise DeploymentError("Install the hash-locked deployment requirements before live SFTP upload.") from None
        # The library must not log server-controlled responses or authentication
        # diagnostics. The script emits only its own redacted progress/errors.
        private_log = logging.getLogger("paramiko")
        private_log.handlers = [logging.NullHandler()]
        private_log.propagate = False
        private_log.disabled = True
        logging.getLogger("paramiko.transport").disabled = True
        connection = socket_factory((host, 222), timeout=30)
        transport = ssh_backend.Transport(connection)
        transport.banner_timeout = 30
        transport.auth_timeout = 30
        transport.channel_timeout = 30
        security = transport.get_security_options()
        pinned_types = {kind for kind, _ in pins}
        key_types = tuple(
            algorithm for algorithm in security.key_types
            if (algorithm in pinned_types and algorithm != "ssh-rsa")
            or (algorithm in ("rsa-sha2-256", "rsa-sha2-512") and "ssh-rsa" in pinned_types)
        )
        if not key_types:
            raise DeploymentError("No supported secure SSH host-key algorithm matches FTP_KNOWN_HOSTS.")
        security.key_types = key_types
        stage = "SSH handshake"
        transport.start_client(timeout=30)
        stage = "SSH host key verification"
        server_key = transport.get_remote_server_key()
        if not any(kind == server_key.get_name() and hmac.compare_digest(wire, server_key.asbytes()) for kind, wire in pins):
            raise DeploymentError("SSH host key does not match FTP_KNOWN_HOSTS; no credentials were sent.")
        stage = "authentication"
        transport.auth_password(username, password, fallback=False)
        if not transport.is_authenticated():
            raise DeploymentError("SFTP authentication did not complete.")
        stage = "SFTP channel"
        sftp = ssh_backend.SFTPClient.from_transport(transport)
        sftp.get_channel().settimeout(30)
        stage = "target directory validation"
        sftp.chdir(remote_dir)
        root = _safe_pwd(sftp)
        if root == "/" and not allow_scoped_root:
            raise DeploymentError("Refusing to upload to the server root without DEPLOY_ALLOW_SCOPED_ROOT=true.")
        all_files = plan.files + (plan.manifest,)
        _ensure_directories(sftp, root, all_files)
        staged = []
        stage = "staging files"
        for file in all_files:
            final_path = posixpath.join(root, file.path)
            parent, basename = posixpath.split(final_path)
            temporary = posixpath.join(parent, f".{basename}.insertcreator-{plan.revision}.upload")
            sftp.putfo(io.BytesIO(file.data), temporary, file_size=len(file.data), confirm=True)
            if sftp.stat(temporary).st_size != len(file.data):
                raise DeploymentError("A staged file has an unexpected size; activation was stopped.")
            staged.append((temporary, final_path))
        stage = "activating files"
        # All uploads and size checks finish before the first rename.
        # An interrupted activation can expose a mixed release; retry the tested
        # revision to finish. The marker is always promoted last.
        for temporary, final_path in staged:
            _activate_file(sftp, temporary, final_path)
    except DeploymentError:
        raise
    except Exception as error:
        # Server responses can echo credentials. Never print or chain them.
        raise DeploymentError(f"SFTP failed during {stage} ({type(error).__name__}). Server details were suppressed to protect credentials.") from None
    finally:
        for resource in (sftp, transport, connection):
            if resource is None:
                continue
            try:
                resource.close()
            except Exception:
                pass


def main(argv=None, *, environ: Mapping[str, str] | None = None, ssh_backend=None, socket_factory=socket.create_connection) -> int:
    environ = os.environ if environ is None else environ
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source", type=Path, default=Path(__file__).resolve().parent.parent / "dist")
    parser.add_argument("--revision", default=environ.get("GITHUB_SHA", ""))
    parser.add_argument("--dry-run", action="store_true", help="Validate the local package without credentials or network access.")
    args = parser.parse_args(argv)
    try:
        plan = build_plan(args.source, args.revision)
        allow_scoped_root = environ.get("DEPLOY_ALLOW_SCOPED_ROOT", "false").lower() == "true"
        remote_dir = validate_remote_dir(environ.get("DEPLOY_REMOTE_DIR", "public_html"), allow_scoped_root)
        total = sum(len(file.data) for file in plan.files)
        if args.dry_run:
            print(f"Dry run OK: {len(plan.files)} static files, {total} bytes; revision {plan.revision}; no server connection.")
            return 0
        deploy(
            plan,
            host=environ.get("FTP_HOST", ""),
            username=environ.get("FTP_USERNAME", ""),
            password=environ.get("FTP_PASSWORD", ""),
            known_hosts=environ.get("FTP_KNOWN_HOSTS", ""),
            remote_dir=remote_dir,
            allow_scoped_root=allow_scoped_root,
            ssh_backend=ssh_backend,
            socket_factory=socket_factory,
        )
        print(f"SFTP upload complete: {len(plan.files)} static files; revision {plan.revision}. Verify the public HTTPS deployment marker.")
        return 0
    except DeploymentError as error:
        print(f"Deployment stopped: {error}", file=sys.stderr)
        return 1
    except Exception as error:
        print(f"Deployment stopped ({type(error).__name__}); details suppressed to protect credentials.", file=sys.stderr)
        return 1


if __name__ == "__main__":
    raise SystemExit(main())
